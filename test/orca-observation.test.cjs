 assert.equal((await control('resume')).status,400);
 assert.equal((await control('revise')).status,200);assert.equal(read(file).nodes.node.resultStale,true);
 assert.equal((await control('approve')).status,400);
 atomic(file,recovered);
 assert.equal((await control('approve')).status,200);
 assert.equal(read(file).status,'succeeded');assert.equal(read(file).nodes.node.confirmedByUser,true);
 assert.equal((await control('approve')).status,400);
 // Real execution failures and obsolete tree runs must remain failures.
