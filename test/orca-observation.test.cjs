'use strict';
const test=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs'),os=require('node:os'),path=require('node:path');
const {OrcaObservation,screenEvidence}=require('../lib/orca-observation.cjs');
const binding={backend:'orca',tool:'codex',handle:'term-1',incarnationId:'inc-1',worktreeId:'wt-1',hostId:'ssh:fixture',promptSent:true,executionStarted:false,notificationMode:'manual',phase:'start-unconfirmed'};
